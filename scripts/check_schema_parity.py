"""Check database schema parity between baseline init SQL and fresh Alembic migrations."""

import argparse
import difflib
import hashlib
import os
from pathlib import Path
import subprocess
import sys
from typing import List, Tuple


def load_env_file() -> None:
    """Load environment variables from a local .env file if present.

    Purpose:
        Ensure configuration variables like POSTGRES_PASSWORD and POSTGRES_HOST_PORT
        are available without overwriting existing environment variables.
    """
    env_path = Path(__file__).resolve().parent.parent / ".env"
    if not env_path.is_file():
        return
    for line in env_path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, val = stripped.split("=", 1)
        key = key.strip()
        val = val.strip().strip("'\"")
        if key not in os.environ:
            os.environ[key] = val


def normalize_schema_dump(text: str) -> str:
    """Normalize pg_dump schema text by removing comments, blank lines, and psql directives.

    Purpose:
        Isolate pure DDL semantics from pg_dump headers, comments, and session settings.

    Inputs:
        text (str): Raw schema dump text generated by pg_dump.

    Outputs:
        str: Cleaned, normalized DDL string with uniform newlines.

    Key Logic:
        Iterates line by line, stripping whitespace and discarding blank lines, SQL comment
        lines starting with '--', and psql directives starting with '\\restrict' or '\\unrestrict'.
        Returns remaining DDL lines joined by newline.

    Complexity:
        Time: O(L) where L is the number of lines in the dump.
        Space: O(N) where N is total characters in normalized DDL.
    """
    clean_lines: List[str] = []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        if stripped.startswith("--"):
            continue
        if stripped.startswith("\\restrict") or stripped.startswith("\\unrestrict"):
            continue
        clean_lines.append(stripped)
    return "\n".join(clean_lines) + ("\n" if clean_lines else "")


REQUIRED_TABLES: Tuple[str, ...] = (
    "CREATE TABLE public.telemetry_events",
    "CREATE TABLE public.tenants",
    "CREATE TABLE public.run_manifests",
    "CREATE TABLE public.alembic_version",
    "CREATE TABLE public.usage_events",
)


def require_tables(dump: str, db_name: str) -> None:
    """Verify that a schema dump contains all required table definitions.

    Purpose:
        Ensure that schema dumps are not empty, truncated, or missing expected tables
        before computing parity diffs.

    Inputs:
        dump (str): Normalized or raw schema dump text.
        db_name (str): Database name being validated (for error reporting).

    Errors:
        SystemExit: If any required table creation statement is missing from dump.
    """
    for table_stmt in REQUIRED_TABLES:
        if table_stmt not in dump:
            table_name = table_stmt.split()[-1]
            sys.stderr.write(
                f"SCHEMA_PARITY: FAIL (missing table {table_name} in {db_name})\n"
            )
            sys.exit(1)


def compare_schema_dumps(dump_init: str, dump_fresh: str) -> Tuple[bool, str, str]:
    """Compare normalized schema dumps and compute digest or unified diff.

    Purpose:
        Determine exact semantic equality between two database schema dumps.

    Inputs:
        dump_init (str): Raw or pre-normalized schema dump from baseline init path.
        dump_fresh (str): Raw or pre-normalized schema dump from fresh Alembic path.

    Outputs:
        Tuple[bool, str, str]: (is_match, sha256_digest_if_match, unified_diff_if_mismatch).

    Key Logic:
        Normalizes both schema dumps using normalize_schema_dump(). If normalized outputs
        are identical, calculates SHA-256 digest of the normalized text and returns (True, sha, "").
        If they differ, generates unified diff between the normalized texts and returns (False, "", diff).

    Complexity:
        Time: O(N) where N is dump size.
        Space: O(N) for normalized diff buffers.
    """
    norm_init = normalize_schema_dump(dump_init)
    norm_fresh = normalize_schema_dump(dump_fresh)
    if norm_init == norm_fresh:
        digest = hashlib.sha256(norm_init.encode("utf-8")).hexdigest()
        return True, digest, ""

    diff_lines = list(
        difflib.unified_diff(
            norm_init.splitlines(keepends=True),
            norm_fresh.splitlines(keepends=True),
            fromfile="parity_init",
            tofile="parity_fresh",
        )
    )
    return False, "", "".join(diff_lines)


def build_compose_prefix(file_args: List[str]) -> List[str]:
    """Build docker compose command prefix with optional file arguments."""
    cmd = ["docker", "compose"]
    for f in file_args:
        cmd.extend(["-f", f])
    return cmd


def execute_psql(compose_prefix: List[str], sql_cmd: str, db: str = "postgres") -> None:
    """Execute SQL command against running postgres container via docker compose exec."""
    cmd = compose_prefix + [
        "exec",
        "-T",
        "postgres",
        "psql",
        "-U",
        "landauer",
        "-d",
        db,
        "-v",
        "ON_ERROR_STOP=1",
        "-c",
        sql_cmd,
    ]
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        raise RuntimeError(f"Failed SQL execution on {db}: {res.stderr.strip()}")


def dump_schema(compose_prefix: List[str], db: str) -> str:
    """Dump database schema via pg_dump running inside postgres container."""
    cmd = compose_prefix + [
        "exec",
        "-T",
        "postgres",
        "pg_dump",
        "-U",
        "landauer",
        "--schema-only",
        "--no-owner",
        "--no-privileges",
        "-d",
        db,
    ]
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        raise RuntimeError(f"Failed pg_dump on {db}: {res.stderr.strip()}")
    return res.stdout


def main() -> int:
    """Run full schema parity check."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "-f",
        "--file",
        action="append",
        default=[],
        help="Compose configuration files (e.g. -f docker-compose.yml -f docker-compose.ci.yml)",
    )
    args = parser.parse_args()

    load_env_file()
    compose_prefix = build_compose_prefix(args.file)

    pg_password = os.environ.get("POSTGRES_PASSWORD", "").strip()
    if not pg_password:
        sys.stderr.write("Error: POSTGRES_PASSWORD environment variable is missing or empty.\n")
        return 1
    pg_port = os.environ.get("POSTGRES_HOST_PORT", "5432")
    pg_user = os.environ.get("POSTGRES_USER", "landauer")

    repo_root = Path(__file__).resolve().parent.parent

    # Clean existing scratch databases first
    execute_psql(compose_prefix, "DROP DATABASE IF EXISTS parity_init;")
    execute_psql(compose_prefix, "DROP DATABASE IF EXISTS parity_fresh;")

    try:
        # Create scratch databases
        execute_psql(compose_prefix, "CREATE DATABASE parity_init;")
        execute_psql(compose_prefix, "CREATE DATABASE parity_fresh;")

        # Parity init path: 001_schema.sql -> alembic stamp 0001 -> alembic upgrade head
        init_sql_cmd = compose_prefix + [
            "exec",
            "-T",
            "postgres",
            "psql",
            "-U",
            pg_user,
            "-d",
            "parity_init",
            "-v",
            "ON_ERROR_STOP=1",
            "-f",
            "/docker-entrypoint-initdb.d/001_schema.sql",
        ]
        res_init = subprocess.run(init_sql_cmd, capture_output=True, text=True)
        if res_init.returncode != 0:
            sys.stderr.write(f"Failed init SQL execution: {res_init.stderr.strip()}\n")
            return 1

        env_init = dict(os.environ)
        env_init["LANDAUER_PG_DSN"] = (
            f"postgresql://{pg_user}:{pg_password}@127.0.0.1:{pg_port}/parity_init"
        )
        sub_stamp = subprocess.run(
            [sys.executable, "-m", "alembic", "stamp", "0001"],
            cwd=str(repo_root),
            env=env_init,
            capture_output=True,
            text=True,
        )
        if sub_stamp.returncode != 0:
            sys.stderr.write(f"alembic stamp 0001 failed: {sub_stamp.stderr.strip()}\n")
            return 1

        sub_up_init = subprocess.run(
            [sys.executable, "-m", "alembic", "upgrade", "head"],
            cwd=str(repo_root),
            env=env_init,
            capture_output=True,
            text=True,
        )
        if sub_up_init.returncode != 0:
            sys.stderr.write(f"alembic upgrade head failed on parity_init: {sub_up_init.stderr.strip()}\n")
            return 1

        # Parity fresh path: alembic upgrade head directly from scratch
        env_fresh = dict(os.environ)
        env_fresh["LANDAUER_PG_DSN"] = (
            f"postgresql://{pg_user}:{pg_password}@127.0.0.1:{pg_port}/parity_fresh"
        )
        sub_up_fresh = subprocess.run(
            [sys.executable, "-m", "alembic", "upgrade", "head"],
            cwd=str(repo_root),
            env=env_fresh,
            capture_output=True,
            text=True,
        )
        if sub_up_fresh.returncode != 0:
            sys.stderr.write(f"alembic upgrade head failed on parity_fresh: {sub_up_fresh.stderr.strip()}\n")
            return 1

        # Dump and compare schemas
        dump_init = dump_schema(compose_prefix, "parity_init")
        dump_fresh = dump_schema(compose_prefix, "parity_fresh")

        require_tables(dump_init, "parity_init")
        require_tables(dump_fresh, "parity_fresh")

        is_match, digest, diff = compare_schema_dumps(dump_init, dump_fresh)
        if is_match:
            print(f"SCHEMA_PARITY: PASS {digest}")
            return 0
        else:
            print("SCHEMA_PARITY: FAIL", file=sys.stderr)
            print(diff, file=sys.stderr)
            return 1

    finally:
        # Guarantee scratch databases are dropped
        try:
            execute_psql(compose_prefix, "DROP DATABASE IF EXISTS parity_init;")
            execute_psql(compose_prefix, "DROP DATABASE IF EXISTS parity_fresh;")
        except Exception:
            pass


if __name__ == "__main__":
    sys.exit(main())
